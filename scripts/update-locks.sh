#!/usr/bin/env bash
# Regenerate every hash-pinned lock from its declared requirements file.
#
#   bash scripts/update-locks.sh
#
# Run this after ANY change to requirements*.txt, then commit the locks alongside it.
# tests/unit/test_dependency_lock.py fails when a lock disagrees with its source, which
# is how you find out you forgot.
#
# Dependabot does not know these locks exist -- it edits requirements*.txt only -- so its
# pull requests arrive with the locks stale and the drift guard red. That is the guard
# doing its job, not a bug, but it means somebody has to run this on the Dependabot branch
# and push before the pull request can go green.
#
# There is deliberately NO --check mode. Re-running this a week later legitimately picks
# up new releases of TRANSITIVE packages (requirements.txt pins only the direct ones), so
# a "would regenerating change anything?" gate would turn CI red whenever anyone upstream
# publishes, and a check that goes red for reasons unrelated to the change is a check
# people learn to ignore. The real gate is the drift test, which compares the lock against
# the DECLARED versions and is therefore stable.
set -euo pipefail

cd "$(dirname "$0")/.."

PYTHON_VERSION=3.11

command -v uv >/dev/null || {
  echo "uv is required: https://docs.astral.sh/uv/getting-started/installation/" >&2
  exit 1
}

tmp="$(mktemp -d)"
trap 'rm -rf -- "$tmp"' EXIT

compile() { # <input file> <lock file>
  uv pip compile "$1" --universal --generate-hashes \
    --python-version "$PYTHON_VERSION" --quiet -o "$tmp/out"
  # uv writes the invoking command into the header, including the -o path, so a lock
  # generated via a temp file would differ from an identical one generated in place.
  # Replace the whole header with a fixed line: the file then depends on its inputs only.
  {
    echo "# Generated by scripts/update-locks.sh -- do not edit by hand."
    echo "# Source: $1 (uv pip compile --universal --generate-hashes --python-version $PYTHON_VERSION)"
    sed '/^# This file was autogenerated by uv/d; /^#    uv pip compile/d' "$tmp/out"
  } > "$2"
}

compile requirements.txt requirements.lock
compile requirements-dev.txt requirements-dev.lock

# The lint job installs only ruff. Its version comes from requirements-dev.txt so the two
# can never disagree about which ruff runs.
grep -E '^ruff==' requirements-dev.txt > "$tmp/lint.in" || {
  echo "requirements-dev.txt has no pinned ruff== line" >&2
  exit 1
}
compile "$tmp/lint.in" requirements-lint.lock

echo "regenerated: requirements.lock requirements-dev.lock requirements-lint.lock"
